function writeOrCheck(path, next) {
	if (!writeMode) {
		let current;
		try {
			current = readFileSync(path, "utf8");
		} catch {
			console.error(`DOC3 table gate: missing ${relative(packageRoot, path)}`);
			process.exitCode = 1;
			return;
		}
		if (current !== next) {
			console.error(
				`DOC3 table gate: ${relative(packageRoot, path)} drifted. Run pnpm --filter @input/pen-docs generate:tables`,
			);
			process.exitCode = 1;
		}
		return;
	}
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, next);
}

