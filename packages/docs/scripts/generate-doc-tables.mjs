const SINK_RE =
	/(?:\.emit|emit)\(\s*["']diagnostic["']|onDiagnostic\?\.\(|\bemit\w*Diagnostic\s*\(|_emitLifecycleDiagnostic\s*\(|clipboardFallback\s*\(/;

const CODE_LITERAL_RE = /\bcode\s*:\s*(?:["']([^"']+)["']|([A-Z][A-Z0-9_]*))/g;

const TERNARY_CODES_RE =
	/\bcode\s*:\s*[^,\n{]+?\?\s*["']([^"']+)["']\s*:\s*["']([^"']+)["']/;

const CONST_STRING_RE =
	/(?:export\s+)?const\s+([A-Z][A-Z0-9_]*)\s*=\s*["']([^"']+)["']/g;

const NAMED_CODE_CONST_RE = /(?:CODE|DIAGNOSTIC_CODE)$/;

const SEARCH_HELPER_RE =
	/emitSearchDiagnostic\s*\(\s*[^,]+,\s*(["']([^"']+)["']|([A-Z][A-Z0-9_]*))/g;

const LIFECYCLE_HELPER_RE = /_emitLifecycleDiagnostic\s*\(\s*["']([^"']+)["']/g;

const CLIPBOARD_HELPER_RE = /clipboardFallback\s*\(\s*["']([^"']+)["']/g;

function walkFiles(directory, files = []) {
	const entries = readdirSync(directory, { withFileTypes: true });
	for (const entry of entries) {
		if (SKIP_DIR_NAMES.has(entry.name)) {
			continue;
		}
		const path = join(directory, entry.name);
		if (entry.isDirectory()) {
			walkFiles(path, files);
			continue;
		}
		if (!/\.tsx?$/.test(entry.name)) {
			continue;
		}
		if (/\.test\.tsx?$/.test(entry.name)) {
			continue;
		}
		files.push(path);
	}
	return files;
}

function extractBalanced(source, startBrace) {
	return extractBalancedPair(source, startBrace);
}

function extractBalancedPair(source, start) {
	const open = source[start];
	const close = open === "{" ? "}" : open === "[" ? "]" : null;
	if (!close) {
		throw new Error(`expected { or [ at ${start}`);
	}
	let depth = 0;
	let quote = null;
	let escaped = false;
	for (let index = start; index < source.length; index += 1) {
		const char = source[index];
		if (quote) {
			if (escaped) {
				escaped = false;
				continue;
			}
			if (char === "\\") {
				escaped = true;
				continue;
			}
			if (char === quote) {
				quote = null;
			}
			continue;
		}
		if (char === '"' || char === "'" || char === "`") {
			quote = char;
			continue;
		}
		if (char === open) {
			depth += 1;
		} else if (char === close) {
			depth -= 1;
			if (depth === 0) {
				return source.slice(start, index + 1);
			}
		}
	}
	throw new Error(`unbalanced ${open}${close}`);
}

function parseObjectEntries(objectText) {
	const body = objectText.slice(1, -1);
	const entries = [];
	let index = 0;
	while (index < body.length) {
		while (index < body.length && /[\s,]/.test(body[index])) {
			index += 1;
		}
		if (index >= body.length) {
			break;
		}
		if (body.startsWith("//", index)) {
			const newline = body.indexOf("\n", index);
			index = newline === -1 ? body.length : newline + 1;
			continue;
		}
		if (body[index] === "[") {
			const close = body.indexOf("]", index);
			if (close === -1) {
				break;
			}
			index = close + 1;
			const colon = body.indexOf(":", index);
			if (colon === -1) {
				break;
			}
			index = colon + 1;
			while (index < body.length && /\s/.test(body[index])) {
				index += 1;
			}
			if (body[index] === "{") {
				const nested = extractBalanced(body, index);
				index += nested.length;
			} else {
				const end = body.indexOf(";", index);
				index = end === -1 ? body.length : end + 1;
			}
			continue;
		}
		const quote = body[index];
		let cursor = index;
		let escaped = false;
		let key = "";
		if (quote === '"' || quote === "'") {
			cursor += 1;
			while (cursor < body.length) {
				const char = body[cursor];
				if (escaped) {
					key += char;
					escaped = false;
					cursor += 1;
					continue;
				}
				if (char === "\\") {
					escaped = true;
					cursor += 1;
					continue;
				}
				if (char === quote) {
					break;
				}
				key += char;
				cursor += 1;
			}
			cursor += 1;
		} else if (/[A-Za-z_]/.test(quote)) {
			while (cursor < body.length && /[A-Za-z0-9_]/.test(body[cursor])) {
				key += body[cursor];
				cursor += 1;
			}
		} else {
			index += 1;
			continue;
		}
		while (cursor < body.length && /\s/.test(body[cursor])) {
			cursor += 1;
		}
		if (body[cursor] !== ":") {
			index = cursor;
			continue;
		}
		cursor += 1;
		while (cursor < body.length && /\s/.test(body[cursor])) {
			cursor += 1;
		}
		let value;
		if (body[cursor] === "{") {
			value = extractBalanced(body, cursor);
			cursor += value.length;
		} else if (body[cursor] === '"' || body[cursor] === "'") {
			const valueQuote = body[cursor];
			cursor += 1;
			let text = "";
			escaped = false;
			while (cursor < body.length) {
				const char = body[cursor];
				if (escaped) {
					text += char;
					escaped = false;
					cursor += 1;
					continue;
				}
				if (char === "\\") {
					escaped = true;
					cursor += 1;
					continue;
				}
				if (char === valueQuote) {
					break;
				}
				text += char;
				cursor += 1;
			}
			value = text;
			cursor += 1;
		} else {
			const end = findValueEnd(body, cursor);
			value = body.slice(cursor, end).trim();
			cursor = end;
		}
		entries.push({ key, value });
		index = cursor;
	}
	return entries;
}

function findValueEnd(text, start) {
	for (let index = start; index < text.length; index += 1) {
		if (text[index] === "," || text[index] === ";") {
			return index;
		}
	}
	return text.length;
}

function parsePluralValue(objectText) {
	const entries = parseObjectEntries(objectText);
	const plural = {};
	for (const entry of entries) {
		if (typeof entry.value === "string") {
			plural[entry.key] = entry.value;
		}
	}
	return plural;
}

function parseParamNames(valueText) {
	if (valueText === "NoMessageParams") {
		return [];
	}
	const mapped = valueText.match(/^A11yMessageParams\[(\w+)\]$/);
	if (mapped) {
		return null;
	}
	if (!valueText.startsWith("{")) {
		return [];
	}
	const names = [];
	const fieldRe = /(\w+)\s*:/g;
	let match = fieldRe.exec(valueText);
	while (match) {
		names.push(match[1]);
		match = fieldRe.exec(valueText);
	}
	return names;
}

function collectMessageRows() {
	const sourcePath = join(
		repoRoot,
		"packages/types/src/types/messages.ts",
	);
	const source = readFileSync(sourcePath, "utf8");

	const a11yParams = {
		blockConverted: ["blockType"],
		undoApplied: ["hint"],
		redoApplied: ["hint"],
		blockSelectionEntered: ["count"],
		blockSelectionChanged: ["count"],
		cellSelectionChanged: ["rows", "columns"],
		suggestionAppeared: [],
		suggestionAccepted: [],
		suggestionRejected: [],
		streamingStarted: [],
		streamingFinished: [],
		findMatches: ["count"],
		atomSelected: ["atomType"],
		collaboratorJoined: ["name"],
		collaboratorEditing: ["name"],
	};

	const paramsStart = source.indexOf("export type MessageParamsByKey");
	if (paramsStart === -1) {
		throw new Error("MessageParamsByKey not found");
	}
	const paramsBrace = source.indexOf("{", paramsStart);
	const paramsObject = extractBalanced(source, paramsBrace);
	const paramEntries = parseObjectEntries(paramsObject);
	const paramsByKey = new Map();
	for (const entry of paramEntries) {
		const names = parseParamNames(entry.value);
		if (names) {
			paramsByKey.set(entry.key, names);
		}
	}

	const catalogStart = source.indexOf(
		"export const DEFAULT_MESSAGE_CATALOG",
	);
	if (catalogStart === -1) {
		throw new Error("DEFAULT_MESSAGE_CATALOG not found");
	}
	const catalogBrace = source.indexOf("{", catalogStart);
	const catalogObject = extractBalanced(source, catalogBrace);
	const catalogEntries = parseObjectEntries(catalogObject);

	const rows = [];
	for (const entry of catalogEntries) {
		const key = entry.key;
		let defaultEnglish;
		let plural = false;
		if (
			typeof entry.value === "string" &&
			/^\{\s*(one|other|zero|two|few|many)\s*:/.test(entry.value)
		) {
			const pluralValue = parsePluralValue(entry.value);
			if (!pluralValue.other) {
				throw new Error(`plural message ${key} is missing "other"`);
			}
			plural = true;
			const parts = Object.keys(pluralValue)
				.sort((left, right) => {
					if (left === "other") {
						return 1;
					}
					if (right === "other") {
						return -1;
					}
					return left.localeCompare(right);
				})
				.map((category) => `${category}: ${pluralValue[category]}`);
			defaultEnglish = parts.join("; ");
		} else if (typeof entry.value === "string") {
			defaultEnglish = entry.value;
		} else {
			throw new Error(`unrecognized catalog value for ${key}`);
		}

		let params = paramsByKey.get(key);
		if (!params && key.startsWith("pen.a11y.")) {
			const shortKey = key.slice("pen.a11y.".length);
			params = a11yParams[shortKey] ?? [];
		}
		params = params ?? [];

		const segments = key.split(".");
		const group =
			segments.length >= 2 ? `${segments[0]}.${segments[1]}` : key;

		rows.push({
			key,
			group,
			defaultEnglish,
			params,
			plural,
		});
	}

	rows.sort((left, right) => left.key.localeCompare(right.key));
	return rows;
}

function collectStringConstants(files) {
	const constants = new Map();
	for (const file of files) {
		const text = readFileSync(file, "utf8");
		CONST_STRING_RE.lastIndex = 0;
		let match = CONST_STRING_RE.exec(text);
		while (match) {
			constants.set(match[1], match[2]);
			match = CONST_STRING_RE.exec(text);
		}
	}
	return constants;
}

function addDiagnostic(rows, code, file, level) {
	let row = rows.get(code);
	if (!row) {
		row = { code, levels: new Set(), sources: new Set() };
		rows.set(code, row);
	}
	if (level) {
		row.levels.add(level);
	}
	row.sources.add(relative(join(repoRoot, "packages"), file));
}

function extractLevels(windowText) {
	const levels = [];
	const levelRe = /\blevel\s*:\s*["'](warn|error|info)["']/g;
	let match = levelRe.exec(windowText);
	while (match) {
		levels.push(match[1]);
		match = levelRe.exec(windowText);
	}
	return levels;
}

function collectCodesFromText(text, file, constants, rows) {
	const levels = extractLevels(text);
	const level = levels[0] ?? "";

	TERNARY_CODES_RE.lastIndex = 0;
	const ternary = TERNARY_CODES_RE.exec(text);
	if (ternary) {
		addDiagnostic(rows, ternary[1], file, level);
		addDiagnostic(rows, ternary[2], file, level);
	}

	CODE_LITERAL_RE.lastIndex = 0;
	let match = CODE_LITERAL_RE.exec(text);
	while (match) {
		const literal = match[1];
		const ident = match[2];
		if (literal && levels.length > 0) {
			addDiagnostic(rows, literal, file, level);
		}
		if (ident && NAMED_CODE_CONST_RE.test(ident)) {
			const code = constants.get(ident);
			const isCrdt = /[/\\]crdt[/\\]/.test(file);
			if (code && (levels.length > 0 || !isCrdt)) {
				addDiagnostic(rows, code, file, level);
			}
		}
		match = CODE_LITERAL_RE.exec(text);
	}

	SEARCH_HELPER_RE.lastIndex = 0;
	let helper = SEARCH_HELPER_RE.exec(text);
	while (helper) {
		const code = helper[2] ?? constants.get(helper[3]);
		if (code) {
			addDiagnostic(rows, code, file, level || "warn");
		}
		helper = SEARCH_HELPER_RE.exec(text);
	}

	LIFECYCLE_HELPER_RE.lastIndex = 0;
	let lifecycle = LIFECYCLE_HELPER_RE.exec(text);
	while (lifecycle) {
		addDiagnostic(rows, lifecycle[1], file, "error");
		lifecycle = LIFECYCLE_HELPER_RE.exec(text);
	}

	CLIPBOARD_HELPER_RE.lastIndex = 0;
	let clipboard = CLIPBOARD_HELPER_RE.exec(text);
	while (clipboard) {
		addDiagnostic(rows, clipboard[1], file, "warn");
		clipboard = CLIPBOARD_HELPER_RE.exec(text);
	}
}

function collectDiagnosticRows() {
	const files = [];
	for (const root of SCAN_ROOTS) {
		walkFiles(join(repoRoot, root), files);
	}
	const constants = collectStringConstants(files);
	const rows = new Map();

	for (const file of files) {
		const text = readFileSync(file, "utf8");
		const hasSink = SINK_RE.test(text);
		const hasEventShape = /\bcode\s*:/.test(text) && /\blevel\s*:/.test(text);
		const hasNamedCode = /code\s*:\s*[A-Z][A-Z0-9_]*CODE/.test(text);
		if (!hasSink && !hasEventShape && !hasNamedCode) {
			continue;
		}

		const lines = text.split("\n");
		for (let lineIndex = 0; lineIndex < lines.length; lineIndex += 1) {
			if (
				!SINK_RE.test(lines[lineIndex]) &&
				!/\bcode\s*:/.test(lines[lineIndex])
			) {
				continue;
			}
			const start = Math.max(0, lineIndex - 48);
			const end = Math.min(lines.length, lineIndex + 28);
			collectCodesFromText(
				lines.slice(start, end).join("\n"),
				file,
				constants,
				rows,
			);
		}
	}

	return [...rows.values()]
		.map((row) => ({
			code: row.code,
			levels: [...row.levels].sort(),
			sources: [...row.sources].sort(),
		}))
		.sort((left, right) => left.code.localeCompare(right.code));
}

function stringify(value) {
	return JSON.stringify(value);
}

function renderMessageCatalogModule(rows) {
	const rowLines = rows.map((row) => {
		const params = row.params.map((name) => stringify(name)).join(", ");
		return [
			"\t{",
			`\t\tkey: ${stringify(row.key)},`,
			`\t\tgroup: ${stringify(row.group)},`,
			`\t\tdefaultEnglish: ${stringify(row.defaultEnglish)},`,
			`\t\tparams: [${params}],`,
			`\t\tplural: ${row.plural},`,
			"\t},",
		].join("\n");
	});

	return [
		`// ${GENERATED_HEADER}`,
		"",
		"export type MessageCatalogRow = {",
		"\treadonly key: string;",
		"\treadonly group: string;",
		"\treadonly defaultEnglish: string;",
		"\treadonly params: readonly string[];",
		"\treadonly plural: boolean;",
		"};",
		"",
		"export const MESSAGE_CATALOG_SOURCE =",
		'\t"packages/types/src/types/messages.ts";',
		"",
		`export const MESSAGE_CATALOG_ROWS: readonly MessageCatalogRow[] = [`,
		...rowLines,
		"];",
		"",
	].join("\n");
}

function renderDiagnosticModule(rows) {
	const rowLines = rows.map((row) => {
		const levels = row.levels.map((level) => stringify(level)).join(", ");
		const sources = row.sources.map((source) => stringify(source)).join(", ");
		return [
			"\t{",
			`\t\tcode: ${stringify(row.code)},`,
			`\t\tlevels: [${levels}],`,
			`\t\tsources: [${sources}],`,
			"\t},",
		].join("\n");
	});

	return [
		`// ${GENERATED_HEADER}`,
		"",
		"export type DiagnosticCodeRow = {",
		"\treadonly code: string;",
		"\treadonly levels: readonly string[];",
		"\treadonly sources: readonly string[];",
		"};",
		"",
		"export const DIAGNOSTIC_CODE_SOURCE =",
		'\t"editor.on(\\"diagnostic\\") emit sites across packages";',
		"",
		`export const DIAGNOSTIC_CODE_ROWS: readonly DiagnosticCodeRow[] = [`,
		...rowLines,
		"];",
		"",
	].join("\n");
}

