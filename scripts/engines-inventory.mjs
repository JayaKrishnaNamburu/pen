#!/usr/bin/env node
/**
 * HOST3 leftover inventory (spec-v2/15-host-integration.md, Wave E step E.4).
 *
 * Reports `engines.node` on every published package against the declared
 * floor (`>=22`). Does not rewrite package.json — E.4 /
 * `sync-package-metadata.mjs` owns the write; this leftover is report-only
 * so it cannot race other manifest editors.
 *
 * Exit is always 0. Quote the missing list instead of flipping.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_REPO_ROOT = path.resolve(SCRIPT_DIR, "..");
const DEFAULT_OUTPUT = path.join(SCRIPT_DIR, "ENGINES.md");

export const NODE_ENGINE = ">=22";

const IGNORE_DIR_NAMES = new Set([
	"node_modules",
	"dist",
	"coverage",
	".turbo",
	".git",
	"playwright-report",
	"test-results",
]);

export function enginesNode(packageJson) {
	const engines = packageJson?.engines;
	if (engines == null || typeof engines !== "object" || Array.isArray(engines)) {
		return null;
	}
	return typeof engines.node === "string" ? engines.node : null;
}

export function enginesStatus(node, floor = NODE_ENGINE) {
	if (node == null) {
		return "missing";
	}
	if (node === floor) {
		return "ok";
	}
	return "mismatch";
}

export function evaluateEngines(packages, floor = NODE_ENGINE) {
	const rows = packages.map((pkg) => {
		const node =
			pkg.node !== undefined ? pkg.node : enginesNode(pkg.packageJson ?? {});
		const status = enginesStatus(node, floor);
		return {
			name: pkg.name,
			dir: pkg.dir,
			node,
			status,
		};
	});
	rows.sort((left, right) => left.name.localeCompare(right.name));
	const missing = rows.filter((row) => row.status !== "ok");
	return {
		floor,
		rows,
		ok: rows.filter((row) => row.status === "ok"),
		missing,
	};
}

export function renderEnginesMarkdown(result) {
	const tableRows = result.rows.map((row) => {
		const node = row.node == null ? "—" : `\`${row.node}\``;
		return `| \`${row.name}\` | \`${row.dir}\` | ${node} | ${row.status} |`;
	});

	const missingLines =
		result.missing.length === 0
			? ["None. Every published package declares `engines.node` `>=22`."]
			: result.missing.map((row) => {
					const declared =
						row.node == null ? "no `engines.node`" : `\`${row.node}\``;
					return `- \`${row.name}\` (\`${row.dir}\`) — ${declared}`;
				});

	return `# HOST3 engines.node inventory

Generated by \`node scripts/engines-inventory.mjs\`. Do not edit by hand.
Do not flip \`package.json\` from this leftover — Wave E.4 / \`sync-package-metadata.mjs\` owns the write.

Floor: \`${result.floor}\` (\`spec-v2/15-host-integration.md\` HOST3). That is the \`setup-node\` pin, not a rounded LTS slogan. Report-only; exit is always 0.

## Published packages

| Package | Directory | engines.node | Status |
| ------- | --------- | ------------ | ------ |
${tableRows.join("\n")}

## Missing \`engines.node\` \`${result.floor}\`

${missingLines.join("\n")}

${result.ok.length} of ${result.rows.length} published packages match the floor. ${result.missing.length} leftover${result.missing.length === 1 ? "" : "s"}.
`;
}

export function formatReport(result) {
	const lines = ["HOST3 leftover engines.node inventory (E.4)"];
	lines.push("");
	lines.push(`floor        ${result.floor}`);
	lines.push(`published    ${result.rows.length}`);
	lines.push(`ok           ${result.ok.length}`);
	lines.push(`missing      ${result.missing.length}`);
	lines.push("");
	if (result.missing.length === 0) {
		lines.push(
			`OK: every published package declares engines.node ${result.floor}.`,
		);
	} else {
		lines.push(`Packages missing engines.node ${result.floor}:`);
		for (const row of result.missing) {
			const declared = row.node == null ? "(absent)" : row.node;
			lines.push(`  ${row.name}  ${row.dir}  ${declared}`);
		}
	}
	lines.push("");
	lines.push("Report-only leftover; package.json was not written. Exit 0.");
	return lines.join("\n");
}

export function runSelfTests() {
	const matching = evaluateEngines([
		{
			name: "@input/pen-core",
			dir: "packages/core",
			node: NODE_ENGINE,
		},
		{
			name: "@input/pen-types",
			dir: "packages/types",
			packageJson: { engines: { node: NODE_ENGINE } },
		},
	]);
	assert(matching.missing.length === 0, "self-test: matching floor is ok");
	assert(matching.ok.length === 2, "self-test: both fixtures counted ok");

	const leftover = evaluateEngines([
		{
			name: "@input/pen-bench",
			dir: "packages/tooling/bench",
			packageJson: { sideEffects: false },
		},
		{
			name: "@input/pen-core",
			dir: "packages/core",
			node: NODE_ENGINE,
		},
		{
			name: "@input/pen-legacy",
			dir: "packages/legacy",
			node: ">=16",
		},
	]);
	assert(
		leftover.missing.map((row) => `${row.name}:${row.status}`).join(",") ===
			"@input/pen-bench:missing,@input/pen-legacy:mismatch",
		"self-test: absent and mismatched engines.node are leftovers",
	);
	assert(
		leftover.ok.length === 1 && leftover.ok[0].name === "@input/pen-core",
		"self-test: matching package stays off the leftover list",
	);

	const markdown = renderEnginesMarkdown(leftover);
	assert(
		markdown.includes("`@input/pen-bench`") &&
			markdown.includes("no `engines.node`") &&
			markdown.includes("`>=16`"),
		"self-test: generated table names leftovers",
	);
	assert(
		enginesNode({ engines: { node: NODE_ENGINE } }) === NODE_ENGINE &&
			enginesNode({}) == null &&
			enginesNode({ engines: { node: 22 } }) == null,
		"self-test: enginesNode reads a string node field only",
	);
	assert(
		enginesStatus(null) === "missing" &&
			enginesStatus(NODE_ENGINE) === "ok" &&
			enginesStatus(">=18") === "mismatch",
		"self-test: status mapping",
	);
}

function assert(condition, message) {
	if (!condition) {
		throw new Error(message);
	}
}

async function collectPackageJsonPaths(directory) {
	const entries = await fs.readdir(directory, { withFileTypes: true });
	const packageJsonPaths = [];

	for (const entry of entries) {
		const entryPath = path.join(directory, entry.name);
		if (entry.isDirectory()) {
			if (!IGNORE_DIR_NAMES.has(entry.name)) {
				packageJsonPaths.push(
					...(await collectPackageJsonPaths(entryPath)),
				);
			}
			continue;
		}
		if (entry.isFile() && entry.name === "package.json") {
			packageJsonPaths.push(entryPath);
		}
	}

	return packageJsonPaths;
}

export async function loadPublishedPackages(repoRoot) {
	const packagesRoot = path.join(repoRoot, "packages");
	const packageJsonPaths = await collectPackageJsonPaths(packagesRoot);
	const packages = [];

	for (const packageJsonPath of packageJsonPaths) {
		const packageJson = JSON.parse(
			await fs.readFile(packageJsonPath, "utf8"),
		);
		if (
			packageJson.private === true ||
			typeof packageJson.name !== "string"
		) {
			continue;
		}
		const dir = path
			.relative(repoRoot, path.dirname(packageJsonPath))
			.split(path.sep)
			.join(path.posix.sep);
		packages.push({
			name: packageJson.name,
			dir,
			packageJson,
			node: enginesNode(packageJson),
		});
	}

	packages.sort((left, right) => left.name.localeCompare(right.name));
	return packages;
}

function parseArgs(argv) {
	let repoRoot = DEFAULT_REPO_ROOT;
	let outputPath = DEFAULT_OUTPUT;
	let stdoutOnly = false;
	let selfTestOnly = false;
	for (let i = 0; i < argv.length; i += 1) {
		const arg = argv[i];
		if (arg === "--self-test") {
			selfTestOnly = true;
			continue;
		}
		if (arg === "--stdout") {
			stdoutOnly = true;
			continue;
		}
		if (arg === "--repo-root") {
			repoRoot = path.resolve(argv[i + 1] ?? "");
			i += 1;
			continue;
		}
		if (arg === "--output") {
			outputPath = path.resolve(argv[i + 1] ?? "");
			i += 1;
			continue;
		}
		throw new Error(`Unknown flag: ${arg}`);
	}
	return { repoRoot, outputPath, stdoutOnly, selfTestOnly };
}

async function main() {
	const args = parseArgs(process.argv.slice(2));
	runSelfTests();
	if (args.selfTestOnly) {
		console.log(
			"HOST3 leftover self-test ok (absent and mismatched engines.node are leftovers; matching floor is not)",
		);
		return;
	}

	const packages = await loadPublishedPackages(args.repoRoot);
	if (packages.length === 0) {
		console.error(
			"engines-inventory: cannot check: packages/**/package.json walk matched 0 published manifests",
		);
		process.exitCode = 1;
		return;
	}
	const result = evaluateEngines(packages);
	const markdown = renderEnginesMarkdown(result);

	if (args.stdoutOnly) {
		process.stdout.write(markdown);
	} else {
		await fs.writeFile(args.outputPath, markdown);
	}

	console.log(formatReport(result));
}

const isDirectRun = process.argv[1] === fileURLToPath(import.meta.url);
if (isDirectRun) {
	main().catch((error) => {
		console.error(error instanceof Error ? error.message : error);
		process.exitCode = 1;
	});
}
